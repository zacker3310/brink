import ms from 'milsymbol';
import type { UnitClass } from '@brink/contracts';

// NATO APP-6 / MIL-STD-2525 unit symbols via milsymbol. Frame shape carries affiliation
// (friend rectangle, hostile diamond, neutral square); fill carries the owning nation's colour;
// a dashed frame marks a planned or last-known position. All formations are brigades (X).

export type Affiliation = 'friend' | 'hostile' | 'neutral' | 'unknown';

const FUNCTION: Record<UnitClass, string> = {
  infantry: 'UCI---',
  mechanized: 'UCIZ--',
  armor: 'UCA---',
  artillery: 'UCF---',
  recon: 'UCR---',
  air: 'UCVRA-',
  drone: 'UCVU--',
};

const AFF: Record<Affiliation, string> = { friend: 'F', hostile: 'H', neutral: 'N', unknown: 'U' };

/** 15-character 2525C symbol code: warfighting, ground unit, brigade echelon. */
export function sidc(cls: UnitClass, aff: Affiliation, planned = false): string {
  return `S${AFF[aff]}G${planned ? 'A' : 'P'}${FUNCTION[cls]}-H---`;
}

export interface SymbolLook {
  cls: UnitClass;
  aff: Affiliation;
  /** Fill colour, usually the owning nation's. */
  fill: string;
  planned?: boolean;
  /** Symbol size in milsymbol units (roughly the frame height in px). */
  size?: number;
  /** Draw the brigade echelon mark above the frame. */
  echelon?: boolean;
}

const DARK = '#0a0c0b';
const INK = { Civilian: DARK, Friend: DARK, Hostile: DARK, Neutral: DARK, Unknown: DARK, Suspect: DARK };

function build(l: SymbolLook) {
  return new ms.Symbol(l.echelon === false ? sidc(l.cls, l.aff, l.planned).slice(0, 11) + '----' : sidc(l.cls, l.aff, l.planned), {
    size: l.size ?? 30,
    fillColor: l.fill,
    frameColor: INK,
    iconColor: DARK,
    outlineColor: 'rgba(10,12,11,0.85)',
    outlineWidth: 2,
    strokeWidth: 4,
    infoFields: false,
  });
}

const svgCache = new Map<string, string>();

/** Inline SVG markup for React. Generated by milsymbol from a fixed code, never user input. */
export function symbolSvg(l: SymbolLook): string {
  const key = JSON.stringify(l);
  let s = svgCache.get(key);
  if (!s) {
    s = build(l).asSVG();
    svgCache.set(key, s);
  }
  return s;
}

export interface SymbolCanvas {
  canvas: HTMLCanvasElement;
  /** Anchor (centre of the frame) in canvas pixels. */
  anchor: { x: number; y: number };
  width: number;
  height: number;
}

const canvasCache = new Map<string, SymbolCanvas>();

/** A canvas rendering for Pixi textures, drawn at `scale` times for crisp zoom. */
export function symbolCanvas(l: SymbolLook, scale = 3): SymbolCanvas {
  const key = `${JSON.stringify(l)}@${scale}`;
  let c = canvasCache.get(key);
  if (!c) {
    const sym = build({ ...l, size: (l.size ?? 30) * scale });
    const canvas = sym.asCanvas();
    const size = sym.getSize();
    c = { canvas, anchor: sym.getAnchor(), width: size.width, height: size.height };
    canvasCache.set(key, c);
  }
  return c;
}
