import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { validateMap } from '@brink/map';
import { generateIndoPac } from './indopac';
import { mapToJson } from './grid';

describe('the Indo-Pacific South map', () => {
  it('is what its grid makes: the committed file is regenerated byte for byte', () => {
    const map = generateIndoPac();
    expect(validateMap(map)).toEqual([]);
    const committed = readFileSync(new URL('../../scenarios/src/maps/indopac.map.json', import.meta.url), 'utf8');
    expect(mapToJson(map)).toBe(committed);
  });
});
