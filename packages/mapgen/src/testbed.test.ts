import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { validateMap } from '@brink/map';
import { mapToJson } from './grid';
import { generateTestbed } from './testbed';

describe('the testbed map', () => {
  it('is what the generator makes: the committed file is regenerated byte for byte', () => {
    const map = generateTestbed();
    expect(validateMap(map)).toEqual([]);
    const committed = readFileSync(new URL('../../scenarios/src/maps/testbed.map.json', import.meta.url), 'utf8');
    expect(mapToJson(map)).toBe(committed);
  });
});
