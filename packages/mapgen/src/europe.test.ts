import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { validateMap } from '@brink/map';
import { EUROPE_GRID, europeMap } from './europe';
import { mapToJson } from './grid';

describe('the European map', () => {
  it('is what its grid makes: the committed file is regenerated byte for byte', () => {
    const map = europeMap();
    expect(validateMap(map)).toEqual([]);
    const committed = readFileSync(new URL('../../scenarios/src/maps/europe.map.json', import.meta.url), 'utf8');
    expect(mapToJson(map)).toBe(committed);
  });

  it('is 56 x 32, every row as wide as the first, and its owner layer is the grid as drawn', () => {
    expect(EUROPE_GRID).toHaveLength(32);
    for (const row of EUROPE_GRID) expect(row).toHaveLength(56);
    expect(europeMap().layers.owner.rows).toEqual([...EUROPE_GRID]);
  });
});
