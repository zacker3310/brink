import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { validateMap } from '@brink/map';
import { generateAntarctica } from './antarctica';
import { mapToJson } from './grid';

describe('the Antarctica map (Black Files)', () => {
  it('is what the generator makes: the committed file is regenerated byte for byte', () => {
    const map = generateAntarctica();
    expect(validateMap(map)).toEqual([]);
    const committed = readFileSync(new URL('../../scenarios/src/maps/antarctica.map.json', import.meta.url), 'utf8');
    expect(mapToJson(map)).toBe(committed);
  });

  it('holds five powers by treaty claim, two neutral states, four digs nobody owns and a black site each', () => {
    const map = generateAntarctica();
    expect(map.nations.filter((n) => n.role === 'power').map((n) => n.id).sort()).toEqual(['australia', 'china', 'russia', 'uk', 'usa']);
    expect(map.nations.filter((n) => n.role === 'minor').map((n) => n.id).sort()).toEqual(['chile', 'norway']);
    const digs = map.sites.filter((s) => s.anomaly === 'excavation');
    expect(digs).toHaveLength(4);
    expect(digs.every((s) => s.owner === null && s.kind === 'objective')).toBe(true);
    for (const n of ['australia', 'china', 'russia', 'uk', 'usa']) expect(map.sites.filter((s) => s.anomaly === 'blacksite' && s.owner === n)).toHaveLength(1);
    // Ice everywhere but Tierra del Fuego; the Drake Passage between them.
    const biomes = new Set(map.layers.biome!.rows.join(''));
    expect([...biomes].sort()).toEqual(['i', 't', '~']);
    expect(map.straits!.map((s) => s.id)).toEqual(['drake']);
    expect(map.seaZones!.map((z) => z.id).sort()).toEqual(['drake-passage', 'ross-sea', 'southern-ocean', 'weddell-sea']);
  });
});
