import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { validateMap } from '@brink/map';
import { generateAmericas } from './americas';
import { mapToJson } from './grid';

describe('the Americas map', () => {
  it('is what its grid makes: the committed file is regenerated byte for byte', () => {
    const map = generateAmericas();
    expect(validateMap(map)).toEqual([]);
    const committed = readFileSync(new URL('../../scenarios/src/maps/americas.map.json', import.meta.url), 'utf8');
    expect(mapToJson(map)).toBe(committed);
  });
});
