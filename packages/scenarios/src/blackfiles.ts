import type { HexKey, NationId, Site, WorldState } from '@brink/contracts';
import { BLACK_FILES } from '@brink/game-data';
import { cellKey, type MapFile, parseMap } from '@brink/map';
import { computeVision, dormantVisitors, newBlackFiles, pairKey, sortedKeys, updateIntel } from '@brink/simulation';
import { buildScenario, type ScenarioSetup } from './build';
import antarcticaMap from './maps/antarctica.map.json';

// The Black Files (MASTER-PLAN Phase 8) as scenarios: the anomaly seeded into a Pacific campaign
// (`applyBlackFiles`, the setup screen's toggle), and the standalone First Contact on the Antarctica
// map. The rules are the simulation's (`blackfiles.ts`); this file only says where things are.

export const FIRST_CONTACT_ID = 'black-files-first-contact';
export const FIRST_CONTACT_TURNS = 30;

/** The Antarctica theatre (generated by packages/mapgen `antarctica.ts`), checked when the module loads. */
export const ANTARCTICA_MAP: MapFile = parseMap(antarcticaMap, 'maps/antarctica.map.json');

const FIRST_CONTACT: ScenarioSetup = {
  scenarioId: FIRST_CONTACT_ID,
  maxTurns: FIRST_CONTACT_TURNS,
  navies: {
    usa: { port: 'McMurdo Station', ships: ['fleet', 'transport'] },
    russia: { port: 'Mirny Observatory', ships: ['fleet', 'transport'] },
    china: { port: 'Zhongshan Station', ships: ['fleet', 'transport'] },
    uk: { port: 'Rothera Station', ships: ['fleet', 'transport'] },
    australia: { port: 'Casey Station', ships: ['fleet', 'transport'] },
  },
};

/** Where the Visitors come up in Antarctica: under the pole, in Ellsworth Land, beside Lake Vostok. */
const ANTARCTICA_INCURSIONS: readonly { at: [number, number]; name: string }[] = [
  { at: [26, 23], name: 'The Pale Lattice' },
  { at: [21, 21], name: 'The Ellsworth Bloom' },
  { at: [29, 22], name: 'The Vostok Spire' },
];

/** Turns the Antarctic Treaty binds every power to peace in First Contact (non-aggression from turn 1). */
export const TREATY_TURNS = 6;

/**
 * Black Files: First Contact. Five powers on the ice by treaty claim, at peace under the Antarctic
 * Treaty (non-aggression through turn 6), Norway and Chile neutral; four digs on the plateau
 * nobody claims. Three artefacts wake the Visitors, or turn 9 whatever was dug.
 */
export function createFirstContact(seed: number): WorldState {
  const w = buildScenario(ANTARCTICA_MAP, seed, FIRST_CONTACT);
  const ids = sortedKeys(w.nations);
  for (let i = 0; i < ids.length; i++)
    for (let j = i + 1; j < ids.length; j++) {
      const [a, b] = [ids[i]!, ids[j]!];
      w.relations[pairKey(a, b)] = 'peace';
      if (!w.nations[a]!.minor && !w.nations[b]!.minor) w.treaties.push({ kind: 'nonaggression', a, b, from: 1, until: TREATY_TURNS });
    }
  // The minor states' capitals are no prize while the treaty holds: the digs are.
  for (const n of ids) if (!w.nations[n]!.minor) w.nations[n]!.objectives = sortedKeys(w.sites).filter((s) => w.sites[s]!.anomaly === 'excavation');
  dormantVisitors(w);
  w.blackFiles = newBlackFiles(w, { wakeAt: 3, wakeTurn: 9, incursions: ANTARCTICA_INCURSIONS.map((i) => ({ key: cellKey(i.at), name: i.name })) });
  refreshIntel(w);
  return w;
}

/** The Pacific's anomalies: the powers' black sites, three digs in the states between them, three incursions. */
const PACIFIC_SITES: readonly { id: string; name: string; at: [number, number]; anomaly: 'blacksite' | 'excavation'; owner: NationId | null; island?: true }[] = [
  { id: 'usa-area-51', name: 'Area 51', at: [28, 11], anomaly: 'blacksite', owner: 'usa' },
  { id: 'usa-bermuda', name: 'Bermuda Deep Site', at: [39, 13], anomaly: 'blacksite', owner: 'usa', island: true },
  { id: 'russia-tunguska', name: 'Tunguska Site', at: [11, 2], anomaly: 'blacksite', owner: 'russia' },
  { id: 'china-gobi', name: 'Gobi Site (Lop Nur)', at: [7, 7], anomaly: 'blacksite', owner: 'china' },
  { id: 'dig-yukon', name: 'Yukon Ice Core', at: [34, 1], anomaly: 'excavation', owner: 'canada' },
  { id: 'dig-gobi', name: 'Gobi Crater', at: [10, 7], anomaly: 'excavation', owner: 'mongolia' },
  { id: 'dig-semipalatinsk', name: 'Semipalatinsk Crater', at: [5, 8], anomaly: 'excavation', owner: 'kazakhstan' },
];

const PACIFIC_INCURSIONS: readonly { at: [number, number]; name: string }[] = [
  { at: [35, 2], name: 'The Yukon Lattice' },
  { at: [10, 6], name: 'The Gobi Bloom' },
  { at: [6, 8], name: 'The Altai Spire' },
];

/**
 * Seed the Black Files into a Pacific campaign (the setup screen's toggle, off by default): Area 51,
 * a Bermuda deep site, Tunguska and a Gobi site as black sites; digs in the Yukon, the Gobi and the
 * Kazakh steppe, held by the states there until a power takes them. Three artefacts wake the
 * Visitors (or turn 16, whatever was dug).
 */
export function applyBlackFiles(w: WorldState): void {
  if (w.blackFiles) return;
  for (const s of PACIFIC_SITES) {
    const key = cellKey(s.at);
    const t = w.tiles[key];
    if (!t || t.siteId || (s.owner && !w.nations[s.owner])) throw new Error(`black files: no room for ${s.name}`);
    if (s.island) {
      // Bermuda: an island raised from the sea hex, a harbour on it.
      t.terrain = 'plains';
      t.owner = s.owner;
      t.port = true;
    } else if (t.owner !== s.owner || t.terrain === 'water') throw new Error(`black files: ${s.name} is not on ${s.owner}'s ground`);
    const site: Site = {
      id: s.id,
      name: s.name,
      kind: 'objective',
      key,
      owner: s.owner,
      originalOwner: s.owner,
      population: 20,
      victoryPoints: s.anomaly === 'excavation' ? 4 : 3,
      yields: { credits: 1, energy: 0, materials: 0, food: 0, industry: 0, research: s.anomaly === 'blacksite' ? 4 : 0 },
      facilities: [],
      anomaly: s.anomaly,
    };
    w.sites[s.id] = site;
    t.siteId = s.id;
    t.infrastructure = Math.max(t.infrastructure, 2);
  }
  dormantVisitors(w);
  w.blackFiles = newBlackFiles(w, { wakeAt: BLACK_FILES.wakeAt, wakeTurn: 16, incursions: PACIFIC_INCURSIONS.map((i) => ({ key: cellKey(i.at), name: i.name })) });
  refreshIntel(w);
}

/** Every power's atlas again, now that the anomalies are on it (as of turn 0, like the builder's). */
function refreshIntel(w: WorldState): void {
  for (const id of sortedKeys(w.nations)) {
    const intel = w.intel[id];
    if (!intel) continue;
    for (const key of sortedKeys(w.tiles)) intel.knownOwner[key] = w.tiles[key]!.owner;
    updateIntel(w, id, computeVision(w, id), 0);
  }
}

/** For tests: the hex an anomaly site of the Pacific stands on. */
export function pacificAnomaly(id: string): HexKey | undefined {
  const s = PACIFIC_SITES.find((x) => x.id === id);
  return s ? cellKey(s.at) : undefined;
}
